#!/usr/bin/env node
// Validates status/status.json and regenerates STATUS.md from it.
// Usage: node status/sync.mjs [--check]   (--check validates only, writes nothing)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const jsonPath = join(here, "status.json");
const mdPath = join(here, "..", "STATUS.md");

const STATES = ["todo", "doing", "blocked", "done"];
const PRIORITIES = ["must", "stretch"];
const TIERS = ["core", "add", "if-time"];

let data;
try {
  data = JSON.parse(readFileSync(jsonPath, "utf8"));
} catch (err) {
  console.error(`status.json is not valid JSON: ${err.message}`);
  process.exit(1);
}

const errors = [];
const isDate = (s) => typeof s === "string" && !Number.isNaN(Date.parse(s));
const need = (cond, msg) => { if (!cond) errors.push(msg); };

need(isDate(data.updated), "updated must be an ISO timestamp");
const teamIds = new Set((data.team ?? []).map((t) => t.id));
need(teamIds.size > 0, "team is empty");
const milestoneIds = new Set((data.milestones ?? []).map((m) => m.id));
for (const m of data.milestones ?? []) need(isDate(m.end), `milestone ${m.id}: end must be an ISO timestamp`);
for (const d of data.deadlines ?? []) need(isDate(d.at), `deadline ${d.id}: at must be an ISO timestamp`);

const seen = new Set();
for (const t of data.tasks ?? []) {
  need(t.id && !seen.has(t.id), `task id missing or duplicated: ${t.id}`);
  seen.add(t.id);
  need(teamIds.has(t.owner), `task ${t.id}: owner "${t.owner}" is not in team`);
  need(milestoneIds.has(t.milestone), `task ${t.id}: milestone "${t.milestone}" does not exist`);
  need(STATES.includes(t.state), `task ${t.id}: state must be one of ${STATES.join("|")}`);
  need(PRIORITIES.includes(t.priority), `task ${t.id}: priority must be must|stretch`);
  need(typeof t.title === "string" && t.title.length > 0, `task ${t.id}: title is empty`);
}
for (const tr of data.tracks ?? []) {
  need(TIERS.includes(tr.tier), `track ${tr.id}: tier must be one of ${TIERS.join("|")}`);
  need(Array.isArray(tr.proofs), `track ${tr.id}: proofs must be a list`);
}
for (const b of data.blockers ?? []) {
  need(["open", "resolved"].includes(b.state), `blocker ${b.id}: state must be open|resolved`);
  need(teamIds.has(b.owner), `blocker ${b.id}: owner "${b.owner}" is not in team`);
}

if (errors.length) {
  console.error("status.json has problems:\n  - " + errors.join("\n  - "));
  process.exit(1);
}
if (process.argv.includes("--check")) {
  console.log("status.json OK");
  process.exit(0);
}

const fmt = (iso) =>
  new Date(iso).toLocaleString("en-US", {
    timeZone: "America/Los_Angeles", weekday: "short", hour: "2-digit", minute: "2-digit", hour12: false,
  });
const mark = { todo: "⬜ todo", doing: "🔵 doing", blocked: "🔴 blocked", done: "✅ done" };
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");

const tasks = data.tasks;
const must = tasks.filter((t) => t.priority === "must");
const pct = (list) => (list.length ? Math.round((100 * list.filter((t) => t.state === "done").length) / list.length) : 0);

const lines = [];
lines.push(`# ${data.project} status`, "");
lines.push(`> Generated by \`node status/sync.mjs\` from \`status/status.json\`. Don't edit by hand.`);
lines.push(`> Last updated ${fmt(data.updated)} PDT. Live board: \`node status/serve.mjs\` → http://localhost:4173`, "");

lines.push(`**Must-ship progress: ${must.filter((t) => t.state === "done").length}/${must.length} (${pct(must)}%)**`, "");
lines.push("| Owner | Role | Name | Must done | Doing | Blocked |", "|---|---|---|---|---|---|");
for (const m of data.team) {
  const mine = tasks.filter((t) => t.owner === m.id);
  const mineMust = mine.filter((t) => t.priority === "must");
  lines.push(`| ${m.id} | ${cell(m.role)} | ${cell(m.name)} | ${mineMust.filter((t) => t.state === "done").length}/${mineMust.length} | ${mine.filter((t) => t.state === "doing").length} | ${mine.filter((t) => t.state === "blocked").length} |`);
}
lines.push("");

lines.push("## Deadlines", "", "| When (PDT) | What |", "|---|---|");
for (const d of data.deadlines) lines.push(`| ${fmt(d.at)} | ${cell(d.label)} |`);
lines.push("");

const openBlockers = data.blockers.filter((b) => b.state === "open");
lines.push(`## Blockers (${openBlockers.length} open)`, "", "| ID | Owner | Question | State | Answer |", "|---|---|---|---|---|");
for (const b of data.blockers) lines.push(`| ${b.id} | ${b.owner} | ${cell(b.text)} | ${b.state} | ${cell(b.answer)} |`);
lines.push("");

lines.push("## Tasks by milestone", "");
for (const m of data.milestones) {
  const list = tasks.filter((t) => t.milestone === m.id);
  if (!list.length) continue;
  lines.push(`### ${m.id} · ${m.window} — ${cell(m.label)}`, "", "| ID | Owner | Task | Priority | State | Note |", "|---|---|---|---|---|---|");
  for (const t of list) lines.push(`| ${t.id} | ${t.owner} | ${cell(t.title)} | ${t.priority} | ${mark[t.state]} | ${cell(t.note)} |`);
  lines.push("");
}

lines.push("## Sponsor track proof", "");
for (const tr of data.tracks) {
  const done = tr.proofs.filter((p) => p.done).length;
  lines.push(`**${cell(tr.name)}** (${tr.tier}, ${cell(tr.prize)}) — ${done}/${tr.proofs.length}`, "");
  for (const p of tr.proofs) lines.push(`- [${p.done ? "x" : " "}] ${p.label}`);
  lines.push("");
}

lines.push("## Cut order when behind", "", data.cutList.map((c, i) => `${i + 1}. ${c}`).join("\n"), "");

writeFileSync(mdPath, lines.join("\n"));
console.log(`status.json OK → wrote STATUS.md (${pct(must)}% of must-ship done)`);
