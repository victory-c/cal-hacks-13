#!/usr/bin/env node
// Generate local credentials without writing them to stdout or Git. Re-running preserves them.
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { parseEnv } from "node:util";
import { fileURLToPath } from "node:url";

const file = fileURLToPath(new URL("../.env.preview", import.meta.url));
if (process.argv.includes("--check")) {
  if (!existsSync(file)) {
    console.error(".env.preview missing; run npm run preview:setup.");
    process.exit(1);
  }
  const values = parseEnv(readFileSync(file, "utf8"));
  for (const key of ["ANTHROPIC_API_KEY", "FACTORY_API_KEY", "JEV_API_KEY", "MOSS_PROJECT_ID", "MOSS_PROJECT_KEY"]) {
    console.log(`${key}: ${values[key] ? "set (value hidden; not live-validated)" : "missing"}`);
  }
  console.log("Provider presence only; run a fresh capture and context query to verify live calls. Jev defaults to https://api.typesafe.ai/v1/systemone.");
  const simulated = values.PREVIEW_ALLOW_SIMULATED === "1";
  const engine = values.DISTILLER || (values.FACTORY_API_KEY ? "droid" : "claude");
  const judge = values.JUDGE_PROVIDER || (values.JEV_API_KEY ? "jev" : "claude");
  const engineKey = { droid: "FACTORY_API_KEY", claude: "ANTHROPIC_API_KEY" }[engine];
  const judgeKey = { jev: "JEV_API_KEY", claude: "ANTHROPIC_API_KEY" }[judge];
  const ready = simulated || (engineKey && judgeKey && values[engineKey] && values[judgeKey]);
  const dispatch=values.DISPATCH_RUNTIME||"claude";
  const dispatchReady=simulated || (dispatch==="claude"?Boolean(values.ANTHROPIC_API_KEY):dispatch==="droid"?Boolean(values.FACTORY_API_KEY):false);
  const clientTokens=new Map((values.CANON_CLIENT_TOKENS??"").split(",").map(pair=>{const at=pair.indexOf("=");return [pair.slice(0,at),pair.slice(at+1)];}));
  const workerTokensReady=["distiller","dispatcher"].every(name=>clientTokens.get(name) && clientTokens.get(name)===values[`CANON_TOKEN_${name.toUpperCase()}`]);
  if(!dispatchReady) console.error("Selected dispatcher needs its provider key; use explicit simulated mode for an offline rehearsal.");
  if(!workerTokensReady) console.error("Internal worker tokens do not match CANON_CLIENT_TOKENS; run preview:setup and reconcile any manually changed worker value.");
  const mossPair = simulated || Boolean(values.MOSS_PROJECT_ID) === Boolean(values.MOSS_PROJECT_KEY);
  console.log(simulated ? "Explicit simulated preview selected." : `Selected distiller: ${engine}; judge: ${judge}.`);
  if (!ready) console.error("Selected real providers need their keys; use PREVIEW_ALLOW_SIMULATED=1 only for an explicit offline rehearsal.");
  if (!mossPair) console.error("Moss needs both MOSS_PROJECT_ID and MOSS_PROJECT_KEY.");
  process.exit(ready && dispatchReady && workerTokensReady && mossPair ? 0 : 1);
}
const secret = () => randomBytes(32).toString("base64url");
const clientNames = ["claude-code", "chatgpt", "teammate-cursor", "distiller", "dispatcher", "ingest", "wags", "axe", "ben", "dollar-bill"];
if (existsSync(file)) {
  let contents=readFileSync(file,"utf8");
  const values=parseEnv(contents);
  const clients=new Map((values.CANON_CLIENT_TOKENS??"").split(",").filter(Boolean).map(pair=>{const at=pair.indexOf("=");return [pair.slice(0,at),pair.slice(at+1)];}));
  for (const name of clientNames) if(!clients.has(name)) clients.set(name,secret());
  const set=(key,value)=>{
    const line=`${key}=${value}`;
    const re=new RegExp(`^${key}=.*$`,"m");
    contents=re.test(contents)?contents.replace(re,()=>line):contents+`\n${line}\n`;
  };
  set("CANON_CLIENT_TOKENS",[...clients].map(([name,token])=>`${name}=${token}`).join(","));
  for(const name of ["distiller","dispatcher","ingest"]) if(!values[`CANON_TOKEN_${name.toUpperCase()}`]) set(`CANON_TOKEN_${name.toUpperCase()}`,clients.get(name));
  if(!values.CANON_PERSON_TOKEN) set("CANON_PERSON_TOKEN",clients.get("ben"));
  if(!values.DISPATCH_RUNTIME) set("DISPATCH_RUNTIME","claude");
  writeFileSync(file,contents,{mode:0o600});
  console.log(".env.preview credentials preserved; missing principal/worker tokens added. Use npm run preview:check.");
  process.exit(0);
}
const password = secret();
const clients = clientNames.map((client) => [client, secret()]);
const valueFor = (client) => clients.find(([name]) => name === client)[1];
const contents = `# Local secret file. Never commit or paste into chat. Generated by npm run preview:setup.
# Default is a loopback-only preview. On the VM, set a real domain + HTTPS; see docs/PREVIEW.md.
PREVIEW_SITE=http://localhost
PREVIEW_PUBLIC_URL=http://localhost:8080
PREVIEW_BIND_ADDRESS=127.0.0.1
PREVIEW_HTTP_PORT=8080
PREVIEW_HTTPS_PORT=8443
# Browser username is team. Share its password directly with teammates.
PREVIEW_PASSWORD=${password}
PREVIEW_ALLOW_SIMULATED=0

# Needed now: the Anthropic console API key, with API credit available.
ANTHROPIC_API_KEY=
DISTILLER=claude
JUDGE_PROVIDER=claude
DISTILL_LIVE=1

# Optional sponsor providers; set DISTILLER=droid and JUDGE_PROVIDER=jev to select them.
FACTORY_API_KEY=
JEV_API_KEY=
JEV_API_URL=https://api.typesafe.ai/v1/systemone
MOSS_PROJECT_ID=
MOSS_PROJECT_KEY=

# Local auth values generated here, not issued by a sponsor.
CANON_CLIENT_TOKENS=${clients.map(([name, token]) => `${name}=${token}`).join(",")}
CANON_TOKEN_DISTILLER=${valueFor("distiller")}
CANON_TOKEN_CLAUDE_CODE=${valueFor("claude-code")}
CANON_TOKEN_DISPATCHER=${valueFor("dispatcher")}
CANON_TOKEN_INGEST=${valueFor("ingest")}
CANON_PERSON_TOKEN=${valueFor("ben")}
# Code-confined Anthropic agent tools; Factory remains available for extraction.
DISPATCH_RUNTIME=claude
`;
writeFileSync(file, contents, { mode: 0o600, flag: "wx" });
console.log("Created .env.preview (owner-readable only), with random client tokens and a team password. No secrets printed.");
console.log("Fill ANTHROPIC_API_KEY locally, then run npm run preview:check. Account links: docs/PREVIEW.md.");
